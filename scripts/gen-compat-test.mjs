// Generates test/types/compat.generated.ts: one compile-time assertion per
// export of every v1 entry point's .d.ts (test/v1-snapshot), checking that the
// v2 export of the same name is assignable to it.
//
//   values (classes, functions, consts):  typeof V2.X  assignable to  typeof V1.X
//   classes, additionally:                instance V2.X assignable to instance V1.X
//   types and interfaces:                 V2.X -> V1.X (what v2 returns fits v1 code)
//                                         V1.X -> V2.X (what v1 code passes fits v2)
//
// A small, explicit list of exceptions covers members where v1's .d.ts did
// not describe v1's own runtime; v2 matches the runtime. Each one is still
// checked, with only the mis-declared member omitted, and the reason is
// written next to it. `npm run test:types` compiles the file.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOT = path.join(root, "test", "v1-snapshot");
// The comparison runs against a copy of v1's .d.ts files with the corrections
// below applied. Each correction makes v1's declaration say what v1's own
// runtime does (verified in test/v1-snapshot/*.js); nothing else is touched.
const V1 = path.join(root, "test", "types", "v1-declared");

export const DECLARATION_CORRECTIONS = [
  {
    file: "index.d.ts",
    what: "DashClient.upload.isAllowed / file return types",
    why:
      "v1 declared isAllowed(): boolean and file(): Promise<{ url, name }>, but services/upload.js returns " +
      "{ allowed, reason } and the server's { success, url, filename, size } (an `if (isAllowed())` check written " +
      "against the declaration was always true at runtime).",
    from: `isAllowed(filename: string): boolean;`,
    to: `isAllowed(filename: string): { allowed: boolean; reason?: string };`,
  },
  {
    file: "index.d.ts",
    what: "DashClient.upload.file return type",
    why: "see above",
    from: `file(file: File, options?: { onProgress?: (percent: number) => void }): Promise<{ url: string; name: string }>;`,
    to: `file(file: File, options?: { onProgress?: (percent: number) => void }): Promise<{ success: boolean; url: string; filename: string; size: number; [key: string]: any }>;`,
  },
];

/**
 * After a store swaps the package, `DashClient` in v1's React declarations
 * resolves to the client the store actually constructs - v2's. Binding it
 * here keeps the comparison about the React API rather than about passing a
 * v1-typed client into v2 components, which cannot happen.
 */
export const BINDINGS = [
  {
    file: "react/index.d.ts",
    from: `import type { DashClient } from "../index";`,
    to: `import type { DashClient } from "../../../../dist/index.js";`,
  },
];

function writeDeclaredCopy() {
  fs.rmSync(V1, { recursive: true, force: true });
  for (const rel of ["index.d.ts", "react/index.d.ts", "utils/index.d.ts", "storage/index.d.ts", "security/index.d.ts"]) {
    let text = fs.readFileSync(path.join(SNAPSHOT, rel), "utf8");
    for (const c of [...DECLARATION_CORRECTIONS, ...BINDINGS].filter((x) => x.file === rel)) {
      if (!text.includes(c.from)) throw new Error(`correction no longer applies: ${c.what || c.from}`);
      text = text.replace(c.from, c.to);
    }
    const dest = path.join(V1, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, text);
  }
  fs.writeFileSync(
    path.join(V1, "README.md"),
    "Generated by scripts/gen-compat-test.mjs from test/v1-snapshot. v1's .d.ts files with the corrections listed in " +
      "DECLARATION_CORRECTIONS applied. Do not edit.\n"
  );
}
writeDeclaredCopy();

const ENTRIES = [
  { alias: "Root", v1: "index.d.ts", v1spec: "./v1-declared/index.js", v2spec: "../../dist/index.js" },
  { alias: "React", v1: "react/index.d.ts", v1spec: "./v1-declared/react/index.js", v2spec: "../../dist/react/index.js" },
  { alias: "DashImage", v1: "react/index.d.ts", v1spec: "./v1-declared/react/index.js", v2spec: "../../dist/react/DashImage.js" },
  { alias: "Utils", v1: "utils/index.d.ts", v1spec: "./v1-declared/utils/index.js", v2spec: "../../dist/utils/index.js" },
  { alias: "Storage", v1: "storage/index.d.ts", v1spec: "./v1-declared/storage/index.js", v2spec: "../../dist/storage/index.js" },
  { alias: "Security", v1: "security/index.d.ts", v1spec: "./v1-declared/security/index.js", v2spec: "../../dist/security/index.js" },
];

/**
 * Classes whose runtime constructor takes the DashClient. Code never passes a
 * v1-typed client to a v2 module, so their static side is checked as
 * "constructible from a v2 DashClient and yields something v1 code accepts"
 * rather than comparing constructor parameter types across versions.
 */
const CLIENT_CONSTRUCTED = /Module$|^PageGroup$/;

function exportsOf(file) {
  const program = ts.createProgram([file], {
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    target: ts.ScriptTarget.ES2020,
    jsx: ts.JsxEmit.ReactJSX,
    skipLibCheck: true,
    noEmit: true,
  });
  const checker = program.getTypeChecker();
  const sf = program.getSourceFile(file);
  const sym = checker.getSymbolAtLocation(sf);
  return checker.getExportsOfModule(sym).map((s) => {
    const target = s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s;
    const f = target.flags;
    const decl = target.declarations && target.declarations[0];
    let typeParams = 0;
    if (decl && (ts.isInterfaceDeclaration(decl) || ts.isTypeAliasDeclaration(decl) || ts.isClassDeclaration(decl))) {
      typeParams = decl.typeParameters ? decl.typeParameters.length : 0;
    }
    return {
      name: s.getName(),
      isValue: !!(f & (ts.SymbolFlags.Value)),
      isClass: !!(f & ts.SymbolFlags.Class),
      isType: !!(f & (ts.SymbolFlags.Type)),
      typeParams,
    };
  });
}

let out = `// GENERATED by scripts/gen-compat-test.mjs - do not edit. Compiled by \`npm run test:types\`.
// Each block fails to compile if v2's export is not assignable to v1's.
/* eslint-disable */

type Assignable<To, From extends To> = From;
declare function v<T>(): T;
`;

const imports = [];
let count = 0;
for (const e of ENTRIES) {
  imports.push(`import type * as V1${e.alias} from "${e.v1spec}";`);
  imports.push(`import type * as V2${e.alias} from "${e.v2spec}";`);
  const list = exportsOf(path.join(V1, e.v1));
  out += `\n// ---- ${e.alias} (${e.v1}) - ${list.length} exports ----\n`;
  for (const x of list) {
    const ta = x.typeParams ? `<${Array(x.typeParams).fill("any").join(", ")}>` : "";
    const a1 = `V1${e.alias}`;
    const a2 = `V2${e.alias}`;
    if (x.name === "default") {
      out += `{ const _: typeof ${a1}.default = v<typeof ${a2}.default>(); }\n`;
      count++;
      continue;
    }
    if (x.isValue) {
      if (x.isClass && CLIENT_CONSTRUCTED.test(x.name)) {
        out += `type _S_${e.alias}_${x.name} = Assignable<new (client: V2Root.DashClient, ...rest: any[]) => ${a1}.${x.name}, typeof ${a2}.${x.name}>;
`;
      } else {
        out += `{ const _: typeof ${a1}.${x.name} = v<typeof ${a2}.${x.name}>(); }
`;
      }
      count++;
    }
    if (x.isClass) {
      out += `type _I_${e.alias}_${x.name} = Assignable<${a1}.${x.name}${ta}, ${a2}.${x.name}${ta}>;
`;
      count++;
    } else if (x.isType) {
      out += `type _O_${e.alias}_${x.name} = Assignable<${a1}.${x.name}${ta}, ${a2}.${x.name}${ta}>;
`;
      out += `type _N_${e.alias}_${x.name} = Assignable<${a2}.${x.name}${ta}, ${a1}.${x.name}${ta}>;
`;
      count += 2;
    }
  }
}

out = `${imports.join("\n")}\n${out}\nexport const ASSERTIONS = ${count};\n`;
const dest = path.join(root, "test", "types", "compat.generated.ts");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)}: ${count} assertions`);
